export type PlaybackPhase = 'PLAYING' | 'VOTING' | 'OPTION_VOTING' | 'GENERATING' | 'COMMERCIAL_BREAK' | 'BLOCKBUSTER_VOTING' | 'MOVIE_VOTING';

export const isOptionVotingPhase = (phase?: PlaybackPhase | string | null): boolean =>
  phase === 'VOTING' || phase === 'OPTION_VOTING';

export const isMovieVotingPhase = (phase?: PlaybackPhase | string | null): boolean =>
  phase === 'BLOCKBUSTER_VOTING' || phase === 'MOVIE_VOTING';

// Total scenes per film: 50 x 15s. Narrative arc:
//   1-10 establishment + central problem, 11-39 development, 40-49 denouement, 50 = THE END
export const TOTAL_STEPS = 50;

export interface BlockbusterCandidate {
  id: 'A' | 'B' | 'C' | 'D';
  title: string;
  logline: string;
  genre: string;
  premise: string;
}

export type ImmersiveAdType = 'commercial_break' | 'in_scene_overlay';

export interface ImmersiveAd {
  id: string;
  brandName: string;
  title: string;
  tagline?: string;
  description?: string;
  type: ImmersiveAdType;
  videoUrl?: string;
  imageUrl?: string;
  ctaText: string;
  ctaUrl?: string;
  perkReward?: string; // e.g. "+50 Audience Community Votes"
  duration: number; // in seconds, default 10s
  isActive: boolean;
  frequencySteps?: number; // e.g. every 5 steps
  stepTrigger?: number; // specific step number or null
  impressions: number;
  clicks: number;
  createdAt?: string;
  /**
   * Screenplay/direction script passed to fal.ai when generating the immersive ad clip.
   * The model is instructed to continue the film world seamlessly while weaving in the brand.
   * If absent the orchestrator falls back to a generic continuation prompt with the brand name.
   */
  cinematicPrompt?: string;
  /**
   * URL of the fal.ai-generated ad clip. Populated at runtime when the commercial break is triggered.
   * Stored in Supabase so the ad can be replayed consistently across sessions.
   */
  generatedAdVideoUrl?: string;
  /**
   * Flag indicating this ad is playing a previously generated archive version.
   */
  isArchiveReplay?: boolean;
}

export interface AdsConfig {
  autoAdsEnabled: boolean;
  adIntervalSteps: number; // Interval of movie steps between ads (e.g. every 5 steps)
  lastAdStep: number;
}

export interface CinemaState {
  movie: Movie;
  phase: PlaybackPhase;
  timeRemaining: number; // in seconds
  phaseDuration?: number; // Initial duration in seconds of current phase
  phaseStartedAt?: string | number; // Epoch ms or ISO string when current phase started
  phaseEndsAt?: string | number; // Epoch ms or ISO string when current phase will end
  totalAudience: number;
  votesA: number;
  votesB: number;
  hasUserVoted?: 'A' | 'B' | null;
  blockbusterUserVoted?: 'A' | 'B' | 'C' | 'D' | null;
  activeStep: MovieStep;
  isLive: boolean;
  isPaused?: boolean;
  isGenerationPaused?: boolean;
  videoModel?: string;
  videoResolution?: string | null;
  blockbusterCandidates?: BlockbusterCandidate[];
  blockbusterVoteCounts?: Record<'A' | 'B' | 'C' | 'D', number>;
  blockbusterWinner?: { id?: 'A' | 'B' | 'C' | 'D'; title: string; logline?: string; genre?: string; premise?: string } | null;
  activeAd?: ImmersiveAd | null;
  adsConfig?: AdsConfig;
  apiStatus?: {
    hasDeepseek: boolean;
    hasFal: boolean;
    isMockMode: boolean;
  };
}

